import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';

/// Lightweight localization (Arabic + English) with typed-by-convention keys.
/// Missing Arabic keys fall back to English, and missing keys render the key.
class AppStrings {
  AppStrings(this.locale);

  final Locale locale;

  static const supportedLocales = [Locale('en'), Locale('ar')];

  static const LocalizationsDelegate<AppStrings> delegate = _AppStringsDelegate();

  bool get isArabic => locale.languageCode == 'ar';

  TextDirection get textDirection => isArabic ? TextDirection.rtl : TextDirection.ltr;

  static AppStrings of(BuildContext context) =>
      Localizations.of<AppStrings>(context, AppStrings) ?? AppStrings(const Locale('en'));

  /// Translates [key]. `{name}` placeholders are replaced with [args].
  String t(String key, [Map<String, String> args = const {}]) {
    var value = (isArabic ? _ar[key] : null) ?? _en[key] ?? key;
    args.forEach((k, v) => value = value.replaceAll('{$k}', v));
    return value;
  }
}

extension AppStringsX on BuildContext {
  AppStrings get s => AppStrings.of(this);
}

class _AppStringsDelegate extends LocalizationsDelegate<AppStrings> {
  const _AppStringsDelegate();

  @override
  bool isSupported(Locale locale) => const ['en', 'ar'].contains(locale.languageCode);

  @override
  Future<AppStrings> load(Locale locale) => SynchronousFuture(AppStrings(locale));

  @override
  bool shouldReload(covariant LocalizationsDelegate<AppStrings> old) => false;
}

